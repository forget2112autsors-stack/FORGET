// Qatorlarni ajratamiz va parse qilamiz
function parseNum(val) {
  if (!val) return 0;
  return parseFloat(String(val).replace(/\s+/g, "").replace(",", ".")) || 0;
}

const products = [];

rawPages.forEach((pgText, pgIdx) => {
  const lines = pgText.trim().split("\n");
  lines.forEach((line) => {
    line = line.trim();
    if (!line) return;

    // Har bir qatorda chap tomonda PE80, o'ng tomonda PE100 bor (yoki faqat bittasi)
    // Regex orqali: (\d+)\s+SDR\s+([\d,\.]+)\s+([\d,\.]+)\s+([\d,\.\+\s]+?)\s+([\d,\.]+)\s+([\d,\.]+)
    // Keling qatorni bo'laklarga ajratamiz
    const tokens = line.split(/\s+/).filter(Boolean);
    
    // Qatorda ikkita "SDR" bormi?
    const sdrIndices = [];
    tokens.forEach((t, i) => { if (t.toUpperCase() === "SDR") sdrIndices.push(i); });

    if (sdrIndices.length === 2) {
      // Chapdagi (PE 80) va o'ngdagi (PE 100)
      const splitIdx = sdrIndices[1] - 1; // o'ngdagi diametrdan boshlanadi
      const leftTokens = tokens.slice(0, splitIdx);
      const rightTokens = tokens.slice(splitIdx);
      parseSide("PE 80", leftTokens);
      parseSide("PE 100", rightTokens);
    } else if (sdrIndices.length === 1) {
      // Faqat bitta (odatda 8-sahifadagilar PE 100)
      const brand = pgIdx === 7 ? "PE 100" : "PE 80";
      parseSide(brand, tokens);
    }
  });
});

function parseSide(brand, tok) {
  // Masalan: ["20", "SDR", "11", "0,116", "2,0", "+", "0,3", "12,5", "1740"]
  // yoki: ["63", "SDR", "26", "0,497", "2,5", "5", "7703,5"]
  if (tok.length < 5) return;
  const d = tok[0];
  const sdrIdx = tok.indexOf("SDR");
  if (sdrIdx < 0) return;
  const sdr = tok[sdrIdx + 1];
  const weight = parseNum(tok[sdrIdx + 2]);
  const price = parseNum(tok[tok.length - 1]);
  const pressure = parseNum(tok[tok.length - 2]);

  // Qalinlik tok[sdrIdx + 3 ... tok.length - 3]
  const thicknessToks = tok.slice(sdrIdx + 3, tok.length - 2);
  const thickness = thicknessToks.join(" ").replace(/\s*\+\s*/g, "+");

  if (!d || !sdr || weight <= 0 || price <= 0) return;

  const rawMaterialName = brand === "PE 80" ? "Polietilen granulasi PE 80" : "Polietilen granulasi PE 100";
  const productName = `Truba ${brand} SDR ${sdr} d.${d} (${pressure} bar, qalinligi ${thickness}mm)`;

  products.push({
    nomi: productName,
    birlik: "metr",
    diametr: parseInt(d),
    sdr: sdr,
    marka: brand,
    bosimBar: pressure,
    vaznKg: weight,
    qalinlikMm: thickness,
    standartNarxi: price,
    foydaNormasi: 15,
    tarkib: [
      {
        nomi: rawMaterialName,
        birlik: "kg",
        norma: weight
      }
    ]
  });
}

console.log("Jami chiqarilgan mahsulotlar soni:", products.length);
fs.writeFileSync(path.join(__dirname, "../kg1_mahsulotlar.json"), JSON.stringify(products, null, 2), "utf8");
